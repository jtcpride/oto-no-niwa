const fs=require('node:fs'),path=require('node:path'),{buildSync}=require('esbuild');
const root=path.resolve(__dirname,'..');
const result=buildSync({absWorkingDir:root,entryPoints:['rendering/three-adapter.js'],bundle:true,format:'iife',minify:true,write:false,target:'es2020',legalComments:'inline'});
// Store as a string so the existing standalone HTML assembler can embed the
// exact same runtime used by the index loader, without CDN or import-map setup.
const source=result.outputFiles[0].text;
fs.writeFileSync(path.join(root,'rendering/three-runtime.js'),'// Generated by npm run build:renderer; do not edit. Three.js MIT license included.\nwindow.FEGThreeSource='+JSON.stringify(source)+';\n');
